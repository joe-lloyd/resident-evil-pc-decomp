// Write the engine's side of her key items, src/game/RebItems.cpp, from
// items.ts: in her mode, her name and her description for each RE1 item id a
// key item of hers takes.
//
//   node tools/rebecca/items/engine.ts          write it
//   node tools/rebecca/items/engine.ts --check  fail if it is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { KEY_ITEMS } from './items.ts';

const here = path.dirname(fileURLToPath(import.meta.url));
export const ENGINE_FILE = path.join(here, '..', '..', '..', 'src', 'game', 'RebItems.cpp');

/** STR() reads its own escapes: a line break is the two characters \ n, written "\\n" in C++. */
const cText = (s: string) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\\\n');

export function engineSource(): string {
  const items = [...KEY_ITEMS].sort((a, b) => a.id - b.id);
  return `// Her key items in her mode (port addition). Generated by
// tools/rebecca/items/engine.ts from tools/rebecca/items/items.ts: edit
// those, not this file.
//
// Each of her key items takes the place of an RE1 item her day never sees.
// In her mode that item id has her name (message_item_name_lookup) and her
// description (set_item_description_message). Chris's and Jill's games never
// reach these tables.
#include "RebItems.h"
#include "PrintText.h"

${items.map((k) => `static constexpr auto s_rebName${k.id.toString(16)} = STR("${cText(k.name)}\\x07");\nstatic constexpr auto s_rebDesc${k.id.toString(16)} = STR("${cText(k.description)}");`).join('\n')}

struct RebItem {
    unsigned char id;
    const unsigned char* name;
    const unsigned char* description;
};

static const RebItem kRebItems[] = {
${items.map((k) => `    { 0x${k.id.toString(16).padStart(2, '0')}, s_rebName${k.id.toString(16)}.bytes, s_rebDesc${k.id.toString(16)}.bytes },  // ${k.step}`).join('\n')}
};

static const RebItem* find(unsigned char itemId)
{
    for (const RebItem& item : kRebItems) {
        if (item.id == itemId) return &item;
    }
    return nullptr;
}

const unsigned char* reb_item_name(unsigned char itemId)
{
    const RebItem* item = find(itemId);
    return item ? item->name : nullptr;
}

const unsigned char* reb_item_description(unsigned char itemId)
{
    const RebItem* item = find(itemId);
    return item ? item->description : nullptr;
}
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const source = engineSource();
  if (process.argv.includes('--check')) {
    if (readFileSync(ENGINE_FILE, 'utf8') !== source) {
      console.error(`${ENGINE_FILE} is out of date: run node tools/rebecca/items/engine.ts`);
      process.exit(1);
    }
  } else {
    writeFileSync(ENGINE_FILE, source);
    console.log(`${ENGINE_FILE}: ${KEY_ITEMS.length} items`);
  }
}
