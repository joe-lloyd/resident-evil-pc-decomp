export type Glyph = readonly (readonly boolean[])[];

export const GLYPHS: ReadonlyMap<string, Glyph> = new Map(
  Object.entries(RAW).map(([ch, rows]) => {
    const parsed = rows === '' ? [] : rows.split('|');
    const grid = Array.from({ length: GLYPH_H }, (_, y) =>
      Array.from({ length: GLYPH_W }, (_, x) => parsed[y]?.[x] === '#'),
    );
    return [ch, grid];
  }),
);

/** The glyph for a character; a character the font lacks is an error, so a typo in a text fails the build. */
export function glyph(ch: string): Glyph {
  const g = GLYPHS.get(ch);
  if (!g) throw new Error(`the file font has no glyph for ${JSON.stringify(ch)}`);
  return g;
}
