// Write the engine's side of Rebecca's files, src/game/RebFiles.cpp, from
// documents.ts: her name for each file slot she fills, where the FILE tab
// draws it, and the order of her two books. The pages themselves come from
// the REB overlay (build.ts), not from here.
//
//   node tools/rebecca/files/engine.ts          write it
//   node tools/rebecca/files/engine.ts --check  fail if it is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { BOOKS, DOCUMENTS } from './documents.ts';

const here = path.dirname(fileURLToPath(import.meta.url));
export const ENGINE_FILE = path.join(here, '..', '..', '..', 'src', 'game', 'RebFiles.cpp');

/** The FILE tab draws a title in the 8 pixel game font with its left edge at x + 0x1E; this centres it on the screen. */
const TITLE_CENTRE = 160;
const titleX = (name: string) => TITLE_CENTRE - 0x1e - [...name].length * 4;

/** A file's name in the FILE tab and the "picked up" message: its title, in capitals as RE1's are. */
export const fileName = (title: string) => title.toUpperCase();

export function engineSource(): string {
  const bySlot = new Map(DOCUMENTS.map((d) => [d.slot, d]));
  const names = Array.from({ length: 16 }, (_, slot) => bySlot.get(slot));
  const book = BOOKS.map((id) => DOCUMENTS.find((d) => d.id === id)!.slot);
  const list = [...book, ...Array(16 - book.length).fill(0xff)].map((n) => `0x${n.toString(16).padStart(2, '0')}`);
  return `// Rebecca's files in her mode (port addition). Generated by
// tools/rebecca/files/engine.ts from tools/rebecca/files/documents.ts:
// edit those, not this file.
//
// A file is item 0x5F + slot. In her mode a slot she fills takes her name
// (message_item_name_lookup), her title position in the FILE tab, and her
// books' order (pickup_screen_init_table). The pages are the REB overlay's
// item_m2/filem_*.pix. Chris's and Jill's games never reach these tables.
#include "RebFiles.h"
#include "PrintText.h"

${names.map((d, slot) => (d ? `static constexpr auto s_rebFile${slot} = STR("${fileName(d.title)}\\x07");` : '')).filter(Boolean).join('\n')}

static const unsigned char* const kRebFileNames[16] = {
${names.map((d, slot) => `    ${d ? `s_rebFile${slot}.bytes` : 'nullptr'},`).join('\n')}
};

static const short kRebFileTitleX[16] = {
${names.map((d) => `    ${d ? titleX(fileName(d.title)) : 0},`).join('\n')}
};

// Her two books of eight, by file slot in the order she finds them; 0xff is empty.
static const unsigned char kRebFileBooks[16] = {
    ${list.slice(0, 8).join(', ')},
    ${list.slice(8).join(', ')},
};

const unsigned char* reb_file_name(unsigned char itemId)
{
    if (itemId < 0x5f || itemId >= 0x5f + 16) return nullptr;
    return kRebFileNames[itemId - 0x5f];
}

short reb_file_title_x(unsigned char fileIndex)
{
    return fileIndex < 16 ? kRebFileTitleX[fileIndex] : 0;
}

void reb_file_books(unsigned char* list)
{
    // Both characters' halves: she plays with the variant bit clear, and the
    // other half must not show RE1's files if the bit is ever set.
    for (int i = 0; i < 16; i++) {
        list[i] = kRebFileBooks[i];
        list[i + 16] = kRebFileBooks[i];
    }
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const src = engineSource();
  if (process.argv.includes('--check')) {
    if (readFileSync(ENGINE_FILE, 'utf8') !== src) throw new Error(`${ENGINE_FILE} is out of date: run node tools/rebecca/files/engine.ts`);
  } else {
    writeFileSync(ENGINE_FILE, src);
    console.log(`wrote ${ENGINE_FILE}`);
  }
}
