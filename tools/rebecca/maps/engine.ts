// Write the engine's side of her maps, src/game/RebMaps.cpp, from the plan
// (plan/maps.ts) and the overview's layout (overview.ts): which area and
// palette block each of her rooms is, the bit that records a visit, which
// map shows each area, the overview's stages, and where the browser finds
// each stage's cut-out and each area's name in the overview picture.
//
//   node tools/rebecca/maps/engine.ts          write it
//   node tools/rebecca/maps/engine.ts --check  fail if it is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { AREAS, AREAS_PER_STAGE, STAGES } from '../plan/maps.ts';
import { BASE_SCREEN, LABEL_H, LABEL_SCREEN, LABEL_W, overview } from './overview.ts';
import { mapIndexOf, mapRooms, stageOf } from './tables.ts';

const here = path.dirname(fileURLToPath(import.meta.url));
export const ENGINE_FILE = path.join(here, '..', '..', '..', 'src', 'game', 'RebMaps.cpp');

const hex = (n: number) => `0x${n.toString(16).padStart(2, '0')}`;
const list = (xs: readonly (number | string)[]) => xs.join(', ');

export function engineSource(): string {
  const rooms = mapRooms();
  const o = overview();
  const stageAreas = STAGES.map((s) => Array.from({ length: AREAS_PER_STAGE }, (_, i) => (s.areas[i] ? hex(AREAS.findIndex((a) => a.id === s.areas[i])) : '0xff')));
  return `// Rebecca's map screen in her mode (port addition). Generated by
// tools/rebecca/maps/engine.ts from tools/rebecca/plan/maps.ts and the
// overview's layout (tools/rebecca/maps/overview.ts): edit those, not this
// file.
//
// Her areas take RE1's eleven map slots (item_m2/map01..0b in the REB
// overlay), her overview its four stage pictures (map0d, map0c, map00,
// map0e), and her six maps RE1's map items 0x4E-0x53. A room's visit is
// her own bit in g_RoomFlags, one per place, below the maps' bits: RE1's
// bits go by stage and room id, and her ids above the stages' own would
// run into the maps and files. Chris's and Jill's games never reach these
// tables.
#include "RebMaps.h"

static const RebMapRoom kRooms[${rooms.length}] = {
${rooms.map((r) => `    { ${r.stage}, ${hex(r.room)}, ${r.area}, ${r.slot}, ${r.bit} },  // ${r.place}`).join('\n')}
};

const RebMaps g_RebMaps = {
    kRooms,
    ${rooms.length},
    // Rooms per area, the map item index that shows it (0xff: none), its overview stage.
    { ${list(AREAS.map((a) => a.places.length))} },
    { ${list(AREAS.map((a) => { const i = mapIndexOf(a.id); return i === undefined ? '0xff' : i; }))} },
    { ${list(AREAS.map((a) => stageOf(a.id)))} },
    // Each stage's areas, in the order up and down step through them.
    {
${stageAreas.map((s, i) => `        { ${list(s)} },  // ${STAGES[i]!.name}`).join('\n')}
    },
    { ${list(STAGES.map((s) => s.areas.length))} },
    // Each stage's cut-out of the mountain: picture u, v; screen x, y; width, height.
    {
${o.markers.map((m, i) => `        { ${m.u}, ${m.v}, ${BASE_SCREEN.x + m.at.x}, ${BASE_SCREEN.y + m.at.y}, ${m.at.w}, ${m.at.h} },  // ${STAGES[i]!.name}`).join('\n')}
    },
    // Each area's name.
    {
${o.labels.map((l, i) => `        { ${l.u}, ${l.v}, ${LABEL_SCREEN.x}, ${LABEL_SCREEN.y}, ${LABEL_W}, ${LABEL_H} },  // ${AREAS[i]!.name}`).join('\n')}
    },
    // The arrows' x, over and under the middle of the name.
    ${LABEL_SCREEN.x + LABEL_W / 2 - 4},
};

const RebMapRoom* reb_map_room(int stage, int room)
{
    for (int i = 0; i < g_RebMaps.roomCount; i++) {
        if (kRooms[i].stage == stage && kRooms[i].room == room) return &kRooms[i];
    }
    return nullptr;
}

int reb_map_visited_bit(int area, int slot)
{
    for (int i = 0; i < g_RebMaps.roomCount; i++) {
        if (kRooms[i].area == area && kRooms[i].slot == slot) return kRooms[i].bit;
    }
    return -1;
}
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const source = engineSource();
  if (process.argv.includes('--check')) {
    if (readFileSync(ENGINE_FILE, 'utf8') !== source) {
      console.error(`${ENGINE_FILE} is out of date: run node tools/rebecca/maps/engine.ts`);
      process.exit(1);
    }
  } else {
    writeFileSync(ENGINE_FILE, source);
    console.log(`${ENGINE_FILE}: ${AREAS.length} areas, ${mapRooms().length} rooms`);
  }
}
